function baseSlide() {
  const s = pptx.addSlide();
  s.background = { color: BG };
  return s;
}

function kicker(s: any, text: string, y = 0.55) {
  s.addText(text.toUpperCase(), {
    x: 0.7, y, w: 12, h: 0.35, fontSize: 12, bold: true,
    color: ACCENT, charSpacing: 3, fontFace: "Consolas",
  });
}

function h1(s: any, text: string, y = 0.95) {
  s.addText(text, {
    x: 0.7, y, w: 12, h: 0.85, fontSize: 32, bold: true, color: INK, fontFace: "Segoe UI",
  });
}

function sourceLine(s: any, text: string) {
  s.addText([{ text: "SOURCE  ", options: { bold: true, color: ACCENT2, fontSize: 9 } }, { text, options: { color: DIM, fontSize: 9 } }], {
    x: 0.7, y: 6.95, w: 12, h: 0.35, fontFace: "Consolas",
  });
}

function statCard(s: any, x: number, y: number, w: number, value: string, label: string, color = ACCENT) {
  s.addShape("roundRect", { x, y, w, h: 1.55, fill: { color: CARD }, line: { color: "232B45" }, rectRadius: 0.08 });
  s.addText(value, { x: x + 0.15, y: y + 0.18, w: w - 0.3, h: 0.75, fontSize: 34, bold: true, color, fontFace: "Segoe UI" });
  s.addText(label, { x: x + 0.15, y: y + 0.95, w: w - 0.3, h: 0.5, fontSize: 11, color: DIM, fontFace: "Segoe UI" });
}

